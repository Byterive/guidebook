"""Writes generated pages into docs/guide-src/<version>/ with edit protection.

Rules: no file -> create. File without generated:true -> the user's, never touched. generated:true and body still matches
page_hash -> overwrite (only if the content changed). generated:true but the body was edited -> keep it and write
<page>.proposed.md. Files starting with "_" are drafts and are never touched."""
from dataclasses import dataclass, field
from pathlib import Path

from .frontmatter import HOME, edit_state, parse
from .hashing import text_hash


@dataclass
class WriteReport:
    created: list = field(default_factory=list)
    updated: list = field(default_factory=list)
    unchanged: list = field(default_factory=list)
    proposed: list = field(default_factory=list)    # edited by the user: new text went to .proposed.md
    skipped_user: list = field(default_factory=list)
    migrated: list = field(default_factory=list)   # old index.md home pages moved to home.md


def _migrate_home(base, shown_prefix, rep, dry_run):
    """Guides made before 0.1.1 kept their home page in index.md, which a project indexer's INDEX.md can overwrite.
    A guidebook-written or indexer-overwritten file is removed (home.md is rewritten); a hand-edited one is moved, not lost."""
    old = base / "index.md"
    if not old.is_file() or (base / HOME).is_file():
        return
    text = old.read_text(encoding="utf-8")
    ours = "GENERATED by tools/build_index.py" in text or edit_state(text) == "pristine"
    rep.migrated.append(f"{shown_prefix}index.md")
    if dry_run:
        return
    if ours:
        old.unlink()
    else:
        old.replace(base / HOME)


def write_pages(src_root, version, pages, dry_run=False) -> WriteReport:
    rep = WriteReport()
    base = Path(src_root) / version
    _migrate_home(base, f"{version}/", rep, dry_run)
    for rel, text in pages:
        target = base / rel
        shown = f"{version}/{rel}"
        if target.name.startswith("_"):
            rep.skipped_user.append(shown)
            continue
        if not target.is_file():
            rep.created.append(shown)
        else:
            old = target.read_text(encoding="utf-8")
            state = edit_state(old)
            if state == "user":
                rep.skipped_user.append(shown)
                continue
            if state == "edited":
                prop = target.with_name(target.stem + ".proposed.md")
                if not prop.is_file() or text_hash(prop.read_text(encoding="utf-8")) != text_hash(text):
                    rep.proposed.append(shown)
                    if not dry_run:
                        prop.write_text(text, encoding="utf-8", newline="\n")
                else:
                    rep.proposed.append(shown)
                continue
            if text_hash(old) == text_hash(text):
                rep.unchanged.append(shown)
                continue
            rep.updated.append(shown)
        if not dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
    return rep


def stale_generated(src_root, version, keep_rels):
    """Generated pages on disk that the current run no longer produces (reported, never deleted)."""
    base = Path(src_root) / version
    if not base.is_dir():
        return []
    out = []
    for p in sorted(base.rglob("*.md")):
        rel = p.relative_to(base).as_posix()
        if rel not in keep_rels and not p.name.endswith(".proposed.md") and parse(p.read_text(encoding="utf-8"))[0].get("generated") is True:
            out.append(f"{version}/{rel}")
    return out
